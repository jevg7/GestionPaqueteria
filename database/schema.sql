-- =====================================================================
-- 19. Rol de la API
-- =====================================================================
-- La API ASP.NET Core no debe conectarse como dueño del esquema (postgres):
-- el dueño puede deshabilitar triggers, borrar y no pasa por RLS. Se conecta con
-- un usuario que pertenece a paqueteria_api, que solo lee, inserta y actualiza.
-- Las migraciones de EF Core sí corren como dueño.
--
-- Crear el usuario de conexión fuera de este script (la contraseña no va al
-- repositorio), por ejemplo desde el SQL Editor de Supabase:
--   create role paqueteria_api_app login password '<desde un gestor de secretos>';
--   grant paqueteria_api to paqueteria_api_app;
--   alter role paqueteria_api_app set search_path = paqueteria, public, extensions;

-- (El rol paqueteria_api se crea al inicio del script: las políticas RLS lo nombran.)

-- Permite al dueño (postgres en Supabase, que no es superusuario) hacer
-- SET ROLE paqueteria_api, que usa la prueba de integración.
grant paqueteria_api to current_user;

grant usage on schema paqueteria to paqueteria_api;
grant select, insert, update on all tables in schema paqueteria to paqueteria_api;
grant delete on usuario_roles to paqueteria_api;
-- La auditoría solo se inserta (vía triggers) y se lee.
revoke update on audit_logs from paqueteria_api;
grant usage, select on all sequences in schema paqueteria to paqueteria_api;
grant execute on all functions in schema paqueteria to paqueteria_api;

-- Tablas y secuencias que creen futuras migraciones heredan los mismos permisos.
alter default privileges in schema paqueteria
  grant select, insert, update on tables to paqueteria_api;
alter default privileges in schema paqueteria
  grant usage, select on sequences to paqueteria_api;
alter default privileges in schema paqueteria
  grant execute on functions to paqueteria_api;
