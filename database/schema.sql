-- =====================================================================
-- Sistema de Gestión de Paquetería — Esquema de base de datos v2 (SaaS multi-agencia)
-- Motor: PostgreSQL 15+ (Supabase)
--
-- Convenciones:
--   * Tablas y columnas en español, snake_case, tablas en plural.
--   * Claves primarias sustitutas (identity). Códigos de negocio aparte
--     (CLI-000001, PKG-000001, AIR-2026-0001, FAC-000001), numerados por agencia.
--   * Dinero: NUMERIC(18,2). Tarifas y tipos de cambio: NUMERIC(12,4). Peso: NUMERIC(10,2) en libras.
--   * Fechas-hora: TIMESTAMPTZ (UTC en la BD; la API convierte a hora local).
--   * Sin borrado físico: activo=false, estados o anulación. DELETE y TRUNCATE
--     están bloqueados por triggers y el rol de la API no tiene esos privilegios.
--   * Enumeraciones pequeñas y cerradas: VARCHAR + CHECK.
--
-- Multi-agencia (docs/diseno-multiagencia.md):
--   * Varias agencias usan la plataforma; cada una ve solo sus datos.
--   * Cada tabla de agencia tiene agencia_id con DEFAULT fn_agencia_actual(),
--     que lee la variable de sesión paqueteria.agencia_id (la fija la API).
--   * Row Level Security: el rol de la API solo ve y escribe filas de su agencia.
--   * Claves foráneas compuestas (id, agencia_id): una fila solo referencia
--     filas de su misma agencia (las FK no pasan por RLS).
--   * Catálogos de la plataforma (estados, roles, métodos de envío) son comunes.
--
-- Códigos de error que usan los triggers (para mapearlos a HTTP en la API):
--   23001 restrict_violation     operación prohibida sobre el registro -> 409
--   23514 check_violation        regla de negocio sobre los valores    -> 400
--   23505 unique_violation       duplicado (p. ej. paquete ya facturado) -> 409
--   42501 insufficient_privilege sin agencia en la sesión (error de programación) -> 500
--
-- El esquema vive en "paqueteria", no en "public", para que la Data API de
-- Supabase (PostgREST) no lo exponga. Solo la API ASP.NET Core accede.
-- =====================================================================

create extension if not exists btree_gist;   -- tarifas sin traslape de vigencia
create extension if not exists pg_trgm;      -- búsqueda de clientes por nombre

create schema if not exists paqueteria;
revoke all on schema paqueteria from public;

set search_path = paqueteria, public, extensions;

-- Rol de la API (sección 19). Se crea primero porque las políticas RLS lo nombran.
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'paqueteria_api') then
    create role paqueteria_api nologin;
  end if;
end $$;


-- =====================================================================
-- 1. Funciones utilitarias
-- =====================================================================

-- Formatea códigos de negocio sin truncar: ('CLI-', 42, 6) -> 'CLI-000042';
-- ('CLI-', 1234567, 6) -> 'CLI-1234567'.
create or replace function fn_formatear_codigo(p_prefijo text, p_numero bigint, p_ancho int)
returns text
language sql immutable
as $$
  select p_prefijo || lpad(p_numero::text, greatest(p_ancho, length(p_numero::text)), '0');
$$;

create or replace function fn_set_actualizado_en()
returns trigger
language plpgsql
as $$
begin
  new.actualizado_en := now();
  return new;
end $$;

-- Protección contra borrado físico. Se usa como trigger por fila (DELETE) y
-- por sentencia (TRUNCATE) en todas las tablas (sección 15).
create or replace function fn_impedir_borrado()
returns trigger
language plpgsql
as $$
begin
  raise exception 'No se permite eliminar registros de %', tg_table_name
    using errcode = 'restrict_violation';
end $$;

-- Agencia de la sesión. La API la fija en cada conexión (paqueteria.agencia_id).
-- Sin agencia no se puede leer ni escribir datos de agencia: es un error de
-- programación, no del usuario.
create or replace function fn_agencia_actual()
returns bigint
language plpgsql stable
as $$
declare
  v_valor text := current_setting('paqueteria.agencia_id', true);
begin
  if v_valor is null or v_valor = '' then
    raise exception 'No hay una agencia en la sesión (paqueteria.agencia_id)'
      using errcode = 'insufficient_privilege';
  end if;
  return v_valor::bigint;
end $$;


-- =====================================================================
-- 2. Plataforma: agencias y sus dueños
-- =====================================================================
-- Tablas de la plataforma, sin RLS: no contienen datos de negocio de las
-- agencias. Solo los dueños de la plataforma las administran (lo controla la API).

create table agencias (
  id               bigint generated by default as identity primary key,
  nombre           varchar(150) not null,
  ruc              varchar(30),
  correo_contacto  varchar(254),
  telefono         varchar(30),
  estado           varchar(20)  not null default 'ACTIVA' check (estado in ('ACTIVA', 'SUSPENDIDA')),
  creado_en        timestamptz  not null default now(),
  actualizado_en   timestamptz  not null default now(),
  constraint ck_agencias_nombre check (btrim(nombre) <> '')
);
create unique index uq_agencias_nombre on agencias (lower(nombre));

-- Dueños de la plataforma: fuera de las agencias; no ven datos de negocio.
create table usuarios_plataforma (
  id              bigint generated by default as identity primary key,
  auth_user_id    uuid         unique,
  nombres         varchar(100) not null,
  apellidos       varchar(100) not null,
  correo          varchar(254) not null,
  activo          boolean      not null default true,
  creado_en       timestamptz  not null default now(),
  actualizado_en  timestamptz  not null default now(),
  constraint ck_usuarios_plataforma_nombres check (btrim(nombres) <> '' and btrim(apellidos) <> '')
);
create unique index uq_usuarios_plataforma_correo on usuarios_plataforma (lower(correo));


-- =====================================================================
-- 3. Correlativos por agencia
-- =====================================================================
-- Las secuencias de PostgreSQL dejan huecos si una transacción falla y son
-- globales. Los códigos se numeran por agencia con una fila contadora que se
-- bloquea y se revierte junto con la transacción (sin huecos en facturas).

create table correlativos (
  agencia_id      bigint      not null default fn_agencia_actual() references agencias (id),
  clave           varchar(30) not null,                  -- 'CLI', 'PKG', 'FAC', 'AIR-2026', 'SEA-2026'
  ultimo_valor    bigint      not null default 0 check (ultimo_valor >= 0),
  actualizado_en  timestamptz not null default now(),
  primary key (agencia_id, clave)
);

create or replace function fn_siguiente_correlativo(p_clave text)
returns bigint
language sql
set search_path = paqueteria, public
as $$
  insert into correlativos as c (agencia_id, clave, ultimo_valor)
  values (fn_agencia_actual(), p_clave, 1)
  on conflict (agencia_id, clave) do update
    set ultimo_valor = c.ultimo_valor + 1,
        actualizado_en = now()
  returning ultimo_valor;
$$;


-- =====================================================================
-- 4. Seguridad: usuarios y roles
-- =====================================================================
-- Las contraseñas las gestiona Supabase Auth. Aquí solo se guarda el
-- vínculo (auth_user_id = claim "sub" del JWT) y los datos del empleado.

create table usuarios (
  id              bigint generated by default as identity primary key,
  agencia_id      bigint       not null default fn_agencia_actual() references agencias (id),
  auth_user_id    uuid         unique,                 -- lo guarda la API al invitar
  nombres         varchar(100) not null,
  apellidos       varchar(100) not null,
  correo          varchar(254) not null,
  telefono        varchar(30),
  activo          boolean      not null default true,
  creado_en       timestamptz  not null default now(),
  actualizado_en  timestamptz  not null default now(),
  constraint uq_usuarios_id_agencia unique (id, agencia_id),
  constraint ck_usuarios_nombres check (btrim(nombres) <> '' and btrim(apellidos) <> '')
);
-- Un correo es una cuenta de Supabase Auth, y una cuenta pertenece a una agencia.
create unique index uq_usuarios_correo on usuarios (lower(correo));
create index ix_usuarios_agencia on usuarios (agencia_id);

-- Catálogo de la plataforma: los mismos roles en todas las agencias.
create table roles (
  id              smallint generated by default as identity primary key,
  codigo          varchar(30)  not null unique,        -- ADMIN, AGENTE, BODEGA, REPARTIDOR
  nombre          varchar(60)  not null,
  descripcion     text,
  activo          boolean      not null default true
);

create table usuario_roles (
  usuario_id      bigint      not null,
  rol_id          smallint    not null references roles (id),
  agencia_id      bigint      not null default fn_agencia_actual(),
  asignado_en     timestamptz not null default now(),
  primary key (usuario_id, rol_id),
  constraint fk_usuario_roles_usuario foreign key (usuario_id, agencia_id) references usuarios (id, agencia_id)
);
create index ix_usuario_roles_rol on usuario_roles (rol_id);


