-- =====================================================================
-- 17. Aislamiento entre agencias: Row Level Security
-- =====================================================================
-- El rol de la API solo ve y escribe filas de la agencia de la sesión. El dueño
-- del esquema (migraciones, mantenimiento) no pasa por RLS.

do $$
declare
  v_tabla text;
begin
  foreach v_tabla in array array[
    'correlativos', 'usuarios', 'usuario_roles', 'ubicaciones', 'rutas', 'tarifas_envio', 'tipos_cambio',
    'clientes', 'embarques', 'paquetes', 'historial_estados_paquete', 'facturas', 'detalles_factura',
    'pagos', 'entregas'
  ] loop
    execute format('alter table %I enable row level security', v_tabla);
    execute format(
      'create policy %I on %I to paqueteria_api using (agencia_id = fn_agencia_actual()) with check (agencia_id = fn_agencia_actual())',
      'pol_' || v_tabla || '_agencia', v_tabla);
  end loop;
end $$;

-- Auditoría: cada agencia lee solo la suya; los triggers insertan cualquier
-- cambio (incluidos los de la plataforma, sin agencia).
alter table audit_logs enable row level security;
create policy pol_audit_logs_leer on audit_logs for select to paqueteria_api
  using (agencia_id = fn_agencia_actual());
create policy pol_audit_logs_insertar on audit_logs for insert to paqueteria_api
  with check (true);

-- Identifica al usuario del token antes de conocer su agencia (RLS no dejaría
-- leer usuarios sin ella). SECURITY DEFINER acotado: solo devuelve lo necesario
-- para autorizar la solicitud.
create or replace function fn_identificar_usuario(p_auth_user_id uuid)
returns table (
  tipo            text,       -- 'AGENCIA' o 'PLATAFORMA'
  usuario_id      bigint,
  agencia_id      bigint,
  activo          boolean,
  agencia_estado  text,
  roles           text[]
)
language sql stable security definer
set search_path = paqueteria, public
as $$
  select 'AGENCIA', u.id, u.agencia_id, u.activo, a.estado,
         array(select r.codigo::text from usuario_roles ur join roles r on r.id = ur.rol_id
               where ur.usuario_id = u.id and r.activo order by r.codigo)
  from usuarios u
  join agencias a on a.id = u.agencia_id
  where u.auth_user_id = p_auth_user_id
  union all
  select 'PLATAFORMA', p.id, null, p.activo, null, array['PLATAFORMA']
  from usuarios_plataforma p
  where p.auth_user_id = p_auth_user_id;
$$;


