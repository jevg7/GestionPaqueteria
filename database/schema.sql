-- =====================================================================
-- 8. Embarques
-- =====================================================================

create table embarques (
  id                      bigint generated by default as identity primary key,
  agencia_id              bigint      not null default fn_agencia_actual(),
  codigo_embarque         varchar(20) not null,        -- lo asigna el trigger si viene null
  ruta_id                 integer     not null,
  metodo_envio_id         smallint    not null references metodos_envio (id),
  estado                  varchar(20) not null default 'ABIERTO'
                          check (estado in ('ABIERTO', 'CERRADO', 'EN_TRANSITO', 'RECIBIDO', 'CANCELADO')),
  fecha_salida            timestamptz,
  fecha_llegada_estimada  date,
  fecha_llegada_real      timestamptz,
  observaciones           text,
  creado_por_usuario_id   bigint      not null,
  creado_en               timestamptz not null default now(),
  actualizado_en          timestamptz not null default now(),
  constraint uq_embarques_codigo unique (agencia_id, codigo_embarque),
  -- Destino de la FK compuesta de paquetes: embarque del mismo método y agencia.
  constraint uq_embarques_id_metodo unique (id, metodo_envio_id, agencia_id),
  constraint fk_embarques_ruta foreign key (ruta_id, agencia_id) references rutas (id, agencia_id),
  constraint fk_embarques_creado_por foreign key (creado_por_usuario_id, agencia_id) references usuarios (id, agencia_id),
  constraint ck_embarques_llegada check (
    fecha_llegada_real is null or (fecha_salida is not null and fecha_llegada_real >= fecha_salida)
  ),
  constraint ck_embarques_estado_fechas check (
    (estado not in ('EN_TRANSITO', 'RECIBIDO') or fecha_salida is not null)
    and (estado <> 'RECIBIDO' or fecha_llegada_real is not null)
  )
);
create index ix_embarques_estado on embarques (agencia_id, estado);
create index ix_embarques_ruta on embarques (ruta_id);
create index ix_embarques_metodo on embarques (metodo_envio_id);
create index ix_embarques_creado_por on embarques (creado_por_usuario_id);

-- Código AIR-2026-0001 / SEA-2026-0001: prefijo del método + año (hora de
-- Managua) + correlativo de la agencia que reinicia cada año.
create or replace function fn_embarques_asignar_codigo()
returns trigger
language plpgsql
set search_path = paqueteria, public
as $$
declare
  v_prefijo char(3);
  v_clave   text;
begin
  if new.codigo_embarque is null then
    select prefijo_embarque into strict v_prefijo
    from metodos_envio where id = new.metodo_envio_id;

    v_clave := v_prefijo || '-' || to_char(now() at time zone 'America/Managua', 'YYYY');
    new.codigo_embarque := fn_formatear_codigo(v_clave || '-', fn_siguiente_correlativo(v_clave), 4);
  end if;
  return new;
end $$;

create trigger trg_embarques_asignar_codigo
  before insert on embarques
  for each row execute function fn_embarques_asignar_codigo();


