-- 5. Catálogos logísticos
-- =====================================================================

-- Catálogo de la plataforma (AEREO, MARITIMO): común a todas las agencias.
create table metodos_envio (
  id                smallint generated by default as identity primary key,
  codigo            varchar(20) not null unique,
  nombre            varchar(50) not null,
  prefijo_embarque  char(3)     not null unique,       -- AIR, SEA
  descripcion       text,
  activo            boolean     not null default true,
  creado_en         timestamptz not null default now(),
  actualizado_en    timestamptz not null default now()
);

-- Catálogo fijo del sistema: los ids son estables y el backend los conoce.
-- No renumerar. Para agregar un estado, usar un id nuevo.
create table estados_paquete (
  id              smallint    primary key,
  codigo          varchar(30) not null unique,
  nombre          varchar(60) not null,
  descripcion     text,
  orden           smallint    not null unique,
  es_final        boolean     not null default false
);

-- Bodegas y agencias físicas de cada agencia (MIA, MGA…).
create table ubicaciones (
  id              integer generated by default as identity primary key,
  agencia_id      bigint       not null default fn_agencia_actual() references agencias (id),
  codigo          varchar(10)  not null,
  nombre          varchar(100) not null,
  pais            char(2)      not null,               -- ISO 3166-1 alfa-2: US, NI
  activo          boolean      not null default true,
  constraint uq_ubicaciones_codigo unique (agencia_id, codigo),
  constraint uq_ubicaciones_id_agencia unique (id, agencia_id)
);

create table rutas (
  id              integer generated by default as identity primary key,
  agencia_id      bigint       not null default fn_agencia_actual(),
  origen_id       integer      not null,
  destino_id      integer      not null,
  nombre          varchar(100) not null,
  activo          boolean      not null default true,
  constraint fk_rutas_origen  foreign key (origen_id, agencia_id)  references ubicaciones (id, agencia_id),
  constraint fk_rutas_destino foreign key (destino_id, agencia_id) references ubicaciones (id, agencia_id),
  constraint ck_rutas_origen_destino check (origen_id <> destino_id),
  constraint uq_rutas_origen_destino unique (agencia_id, origen_id, destino_id),
  constraint uq_rutas_id_agencia unique (id, agencia_id)
);
create index ix_rutas_origen on rutas (origen_id);
create index ix_rutas_destino on rutas (destino_id);


-- =====================================================================
-- 6. Tarifas y tipo de cambio (de cada agencia)
-- =====================================================================
-- Vigencia por fechas. fecha_fin inclusiva; null = vigente sin fin.
-- La BD impide dos tarifas activas del mismo método y agencia con fechas
-- traslapadas, así "la tarifa vigente" siempre es única.

create table tarifas_envio (
  id                     integer generated by default as identity primary key,
  agencia_id             bigint        not null default fn_agencia_actual() references agencias (id),
  metodo_envio_id        smallint      not null references metodos_envio (id),
  precio_por_unidad      numeric(12,4) not null check (precio_por_unidad > 0),
  unidad                 varchar(10)   not null default 'LB' check (unidad in ('LB')),
  moneda                 char(3)       not null default 'USD' check (moneda in ('USD')),
  fecha_inicio           date          not null,
  fecha_fin              date,
  activo                 boolean       not null default true,
  creado_por_usuario_id  bigint,
  creado_en              timestamptz   not null default now(),
  actualizado_en         timestamptz   not null default now(),
  constraint ck_tarifas_vigencia check (fecha_fin is null or fecha_fin >= fecha_inicio),
  -- Destino de la FK compuesta de paquetes: tarifa del mismo método y agencia.
  constraint uq_tarifas_id_metodo unique (id, metodo_envio_id, agencia_id),
  constraint fk_tarifas_creado_por foreign key (creado_por_usuario_id, agencia_id) references usuarios (id, agencia_id),
  constraint ex_tarifas_sin_traslape exclude using gist (
    agencia_id with =,
    metodo_envio_id with =,
    daterange(fecha_inicio, fecha_fin, '[]') with &&
  ) where (activo)
);
create index ix_tarifas_metodo on tarifas_envio (metodo_envio_id);
create index ix_tarifas_creado_por on tarifas_envio (creado_por_usuario_id) where creado_por_usuario_id is not null;

-- Tarifa vigente de la agencia de la sesión. Si no hay, devuelve una fila con
-- todo null: filtrar con "where id is not null".
create or replace function fn_tarifa_vigente(p_metodo_envio_id smallint, p_fecha date default current_date)
returns tarifas_envio
language sql stable
set search_path = paqueteria, public
as $$
  select t.*
  from tarifas_envio t
  where t.agencia_id = fn_agencia_actual()
    and t.metodo_envio_id = p_metodo_envio_id
    and t.activo
    and p_fecha >= t.fecha_inicio
    and (t.fecha_fin is null or p_fecha <= t.fecha_fin)
  limit 1;
$$;

-- Córdobas por dólar de cada día. El vigente para un pago es el más reciente
-- con fecha <= hoy en Managua; cada pago guarda su copia.
create table tipos_cambio (
  id                     integer generated by default as identity primary key,
  agencia_id             bigint        not null default fn_agencia_actual() references agencias (id),
  fecha                  date          not null,
  nio_por_usd            numeric(12,4) not null,
  creado_por_usuario_id  bigint        not null,
  creado_en              timestamptz   not null default now(),
  actualizado_en         timestamptz   not null default now(),
  constraint ck_tipos_cambio_valor check (nio_por_usd > 0),
  constraint uq_tipos_cambio_fecha unique (agencia_id, fecha),
  constraint fk_tipos_cambio_creado_por foreign key (creado_por_usuario_id, agencia_id) references usuarios (id, agencia_id)
);
create index ix_tipos_cambio_creado_por on tipos_cambio (creado_por_usuario_id);


