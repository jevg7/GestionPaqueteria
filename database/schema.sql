-- =====================================================================
-- 11. Facturación
-- =====================================================================
-- Estado de la factura = ciclo de vida del documento (EMITIDA / ANULADA).
-- Estado de pago (PENDIENTE / PARCIAL / PAGADA) y saldo se derivan de los
-- pagos en la vista v_facturas_saldo, para que nunca se contradigan.
--
-- Una factura emitida es financieramente inmutable:
--   * Sus montos, cliente, número y fecha no cambian nunca.
--   * Sus líneas no se modifican ni se borran.
--   * Al confirmar la transacción debe tener al menos una línea y la suma de
--     las líneas debe ser igual a su subtotal. Por eso factura y líneas se
--     crean en la misma transacción; una línea agregada después descuadra la
--     factura y se rechaza.
--   * Solo admite un cambio: EMITIDA -> ANULADA (sin pagos aplicados).
--     Una corrección se hace anulando y emitiendo otra factura.

create table facturas (
  id                bigint generated by default as identity primary key,
  agencia_id        bigint        not null default fn_agencia_actual(),
  numero_factura    varchar(20)   not null
                    default fn_formatear_codigo('FAC-', fn_siguiente_correlativo('FAC'), 6),
  cliente_id        bigint        not null,
  fecha             timestamptz   not null default now(),
  moneda            char(3)       not null default 'USD' check (moneda in ('USD')),
  subtotal          numeric(18,2) not null check (subtotal >= 0),
  descuento         numeric(18,2) not null default 0 check (descuento >= 0),
  impuestos         numeric(18,2) not null default 0 check (impuestos >= 0),
  total             numeric(18,2) not null,
  estado            varchar(20)   not null default 'EMITIDA' check (estado in ('EMITIDA', 'ANULADA')),
  motivo_anulacion  text,
  anulada_en        timestamptz,
  usuario_id        bigint        not null,
  creado_en         timestamptz   not null default now(),
  actualizado_en    timestamptz   not null default now(),
  constraint uq_facturas_numero unique (agencia_id, numero_factura),
  constraint uq_facturas_id_agencia unique (id, agencia_id),
  -- Destino de la FK compuesta de pagos: el pago es del cliente de la factura.
  constraint uq_facturas_id_cliente unique (id, cliente_id, agencia_id),
  constraint fk_facturas_cliente foreign key (cliente_id, agencia_id) references clientes (id, agencia_id),
  constraint fk_facturas_usuario foreign key (usuario_id, agencia_id) references usuarios (id, agencia_id),
  constraint ck_facturas_descuento check (descuento <= subtotal),
  constraint ck_facturas_total check (total = subtotal - descuento + impuestos),
  constraint ck_facturas_anulacion check (
    (estado = 'ANULADA') = (anulada_en is not null and nullif(btrim(motivo_anulacion), '') is not null)
  )
);
create index ix_facturas_cliente on facturas (cliente_id);
create index ix_facturas_fecha on facturas (agencia_id, fecha);
create index ix_facturas_usuario on facturas (usuario_id);

create table detalles_factura (
  id               bigint generated by default as identity primary key,
  agencia_id       bigint        not null default fn_agencia_actual(),
  factura_id       bigint        not null,
  paquete_id       bigint,                                  -- null para cargos no ligados a un paquete (futuro)
  descripcion      varchar(200)  not null,
  cantidad         numeric(10,2) not null check (cantidad > 0),          -- libras facturadas, o 1
  precio_unitario  numeric(12,4) not null check (precio_unitario > 0),   -- tarifa por libra
  subtotal         numeric(18,2) not null check (subtotal > 0),
  constraint fk_detalles_factura foreign key (factura_id, agencia_id) references facturas (id, agencia_id),
  constraint fk_detalles_paquete foreign key (paquete_id, agencia_id) references paquetes (id, agencia_id),
  constraint ck_detalles_subtotal check (subtotal = round(cantidad * precio_unitario, 2))
);
create index ix_detalles_factura on detalles_factura (factura_id);
create index ix_detalles_paquete on detalles_factura (paquete_id) where paquete_id is not null;

-- Un paquete no puede estar en dos facturas vigentes, y debe ser del mismo
-- cliente que la factura. No se agregan líneas a facturas anuladas.
create or replace function fn_detalles_validar()
returns trigger
language plpgsql
set search_path = paqueteria, public
as $$
declare
  v_factura_cliente bigint;
  v_factura_estado  text;
  v_paquete_cliente bigint;
begin
  select cliente_id, estado into v_factura_cliente, v_factura_estado
  from facturas where id = new.factura_id;

  if v_factura_estado = 'ANULADA' then
    raise exception 'No se pueden agregar líneas a una factura anulada'
      using errcode = 'check_violation';
  end if;

  if new.paquete_id is not null then
    -- Bloquea el paquete para que dos facturas simultáneas no lo tomen a la vez.
    select cliente_id into v_paquete_cliente
    from paquetes where id = new.paquete_id
    for update;

    if v_paquete_cliente <> v_factura_cliente then
      raise exception 'El paquete % no pertenece al cliente de la factura', new.paquete_id
        using errcode = 'check_violation';
    end if;

    if exists (
      select 1
      from detalles_factura d
      join facturas f on f.id = d.factura_id
      where d.paquete_id = new.paquete_id
        and f.estado <> 'ANULADA'
        and d.id is distinct from new.id
    ) then
      raise exception 'El paquete % ya está incluido en una factura vigente', new.paquete_id
        using errcode = 'unique_violation';
    end if;
  end if;

  return new;
end $$;

create trigger trg_detalles_validar
  before insert on detalles_factura
  for each row execute function fn_detalles_validar();

create or replace function fn_detalles_inmutable()
returns trigger
language plpgsql
as $$
begin
  raise exception 'Las líneas de una factura no se modifican; anule la factura y emita otra'
    using errcode = 'restrict_violation';
end $$;

create trigger trg_detalles_inmutable
  before update on detalles_factura
  for each row execute function fn_detalles_inmutable();

-- Cuadre de la factura, verificado al confirmar la transacción.
create or replace function fn_facturas_verificar_cuadre()
returns trigger
language plpgsql
set search_path = paqueteria, public
as $$
declare
  v_factura_id  bigint;
  v_subtotal    numeric(18,2);
  v_lineas      int;
  v_suma        numeric(18,2);
begin
  if tg_table_name = 'facturas' then
    v_factura_id := new.id;
  else
    v_factura_id := new.factura_id;
  end if;

  select subtotal into v_subtotal from facturas where id = v_factura_id;
  select count(*), coalesce(sum(subtotal), 0) into v_lineas, v_suma
  from detalles_factura where factura_id = v_factura_id;

  if v_lineas = 0 then
    raise exception 'La factura % no tiene líneas', v_factura_id
      using errcode = 'check_violation';
  end if;

  if v_suma <> v_subtotal then
    raise exception 'La suma de las líneas (%) no coincide con el subtotal de la factura % (%)',
      v_suma, v_factura_id, v_subtotal
      using errcode = 'check_violation';
  end if;

  return null;
end $$;

create constraint trigger ctrg_facturas_cuadre
  after insert on facturas
  deferrable initially deferred
  for each row execute function fn_facturas_verificar_cuadre();

create constraint trigger ctrg_detalles_cuadre
  after insert on detalles_factura
  deferrable initially deferred
  for each row execute function fn_facturas_verificar_cuadre();

-- Inmutabilidad de la cabecera y única transición permitida.
create or replace function fn_facturas_proteger()
returns trigger
language plpgsql
set search_path = paqueteria, public
as $$
begin
  if (new.numero_factura, new.cliente_id, new.fecha, new.moneda, new.subtotal, new.descuento,
      new.impuestos, new.total, new.usuario_id, new.creado_en)
     is distinct from
     (old.numero_factura, old.cliente_id, old.fecha, old.moneda, old.subtotal, old.descuento,
      old.impuestos, old.total, old.usuario_id, old.creado_en) then
    raise exception 'Los datos de la factura % son inmutables; anúlela y emita otra', old.numero_factura
      using errcode = 'restrict_violation';
  end if;

  if old.estado = 'ANULADA'
     and (new.estado, new.motivo_anulacion, new.anulada_en)
         is distinct from (old.estado, old.motivo_anulacion, old.anulada_en) then
    raise exception 'La factura % está anulada y no puede modificarse', old.numero_factura
      using errcode = 'restrict_violation';
  end if;

  if old.estado = 'EMITIDA' and new.estado = 'ANULADA'
     and exists (select 1 from pagos where factura_id = old.id and estado = 'APLICADO') then
    raise exception 'La factura % tiene pagos aplicados; anule los pagos antes de anular la factura', old.numero_factura
      using errcode = 'check_violation';
  end if;

  return new;
end $$;

create trigger trg_facturas_proteger
  before update on facturas
  for each row execute function fn_facturas_proteger();


-- =====================================================================
-- 12. Pagos
-- =====================================================================
-- Admite varios pagos por factura (pagos parciales), en USD o en córdobas.
-- La factura está en USD: monto es lo abonado en USD; en córdobas, el pago
-- guarda los córdobas recibidos y una copia del tipo de cambio usado.
-- Un pago no se borra: se anula con motivo.

create table pagos (
  id                    bigint generated by default as identity primary key,
  agencia_id            bigint        not null default fn_agencia_actual(),
  factura_id            bigint        not null,
  cliente_id            bigint        not null,
  monto                 numeric(18,2) not null check (monto > 0),
  moneda                char(3)       not null default 'USD',
  monto_moneda          numeric(18,2),
  tipo_cambio_aplicado  numeric(12,4),
  metodo_pago           varchar(20)   not null
                        check (metodo_pago in ('EFECTIVO', 'TRANSFERENCIA', 'TARJETA', 'OTRO')),
  referencia            varchar(100),
  fecha                 timestamptz   not null default now(),
  estado                varchar(20)   not null default 'APLICADO' check (estado in ('APLICADO', 'ANULADO')),
  motivo_anulacion      text,
  anulado_en            timestamptz,
  usuario_id            bigint        not null,
  creado_en             timestamptz   not null default now(),
  actualizado_en        timestamptz   not null default now(),
  -- El cliente del pago es el mismo de la factura.
  constraint fk_pagos_factura_cliente foreign key (factura_id, cliente_id, agencia_id)
    references facturas (id, cliente_id, agencia_id),
  constraint fk_pagos_cliente foreign key (cliente_id, agencia_id) references clientes (id, agencia_id),
  constraint fk_pagos_usuario foreign key (usuario_id, agencia_id) references usuarios (id, agencia_id),
  constraint ck_pagos_moneda check (
    (moneda = 'USD' and monto_moneda is null and tipo_cambio_aplicado is null)
    or (moneda = 'NIO' and monto_moneda > 0 and tipo_cambio_aplicado > 0
        and monto = round(monto_moneda / tipo_cambio_aplicado, 2))
  ),
  constraint ck_pagos_anulacion check (
    (estado = 'ANULADO') = (anulado_en is not null and nullif(btrim(motivo_anulacion), '') is not null)
  )
);
create index ix_pagos_factura on pagos (factura_id);
create index ix_pagos_cliente on pagos (cliente_id);
create index ix_pagos_fecha on pagos (agencia_id, fecha);
create index ix_pagos_usuario on pagos (usuario_id);

-- No se paga una factura anulada ni se paga más que su total.
create or replace function fn_pagos_validar()
returns trigger
language plpgsql
set search_path = paqueteria, public
as $$
declare
  v_total   numeric(18,2);
  v_estado  text;
  v_pagado  numeric(18,2);
begin
  if new.estado <> 'APLICADO' then
    return new;
  end if;

  -- Bloquea la factura: serializa pagos concurrentes sobre la misma factura.
  select total, estado into v_total, v_estado
  from facturas where id = new.factura_id
  for update;

  if v_estado = 'ANULADA' then
    raise exception 'No se puede registrar un pago a una factura anulada'
      using errcode = 'check_violation';
  end if;

  select coalesce(sum(monto), 0) into v_pagado
  from pagos
  where factura_id = new.factura_id
    and estado = 'APLICADO'
    and id is distinct from new.id;

  if v_pagado + new.monto > v_total then
    raise exception 'El pago excede el saldo de la factura (saldo: %, pago: %)',
      v_total - v_pagado, new.monto
      using errcode = 'check_violation';
  end if;

  return new;
end $$;

create trigger trg_pagos_validar
  before insert on pagos
  for each row execute function fn_pagos_validar();

-- Un pago registrado es inmutable. Solo admite APLICADO -> ANULADO (con
-- motivo y fecha). Un pago anulado ya no cambia; si hubo un error se
-- registra un pago nuevo.
create or replace function fn_pagos_proteger()
returns trigger
language plpgsql
as $$
begin
  if (new.factura_id, new.cliente_id, new.monto, new.moneda, new.monto_moneda, new.tipo_cambio_aplicado,
      new.metodo_pago, new.referencia, new.fecha, new.usuario_id, new.creado_en)
     is distinct from
     (old.factura_id, old.cliente_id, old.monto, old.moneda, old.monto_moneda, old.tipo_cambio_aplicado,
      old.metodo_pago, old.referencia, old.fecha, old.usuario_id, old.creado_en) then
    raise exception 'Los datos del pago % son inmutables; anúlelo y registre otro', old.id
      using errcode = 'restrict_violation';
  end if;

  if old.estado = 'ANULADO'
     and (new.estado, new.motivo_anulacion, new.anulado_en)
         is distinct from (old.estado, old.motivo_anulacion, old.anulado_en) then
    raise exception 'El pago % está anulado y no puede modificarse', old.id
      using errcode = 'restrict_violation';
  end if;

  return new;
end $$;

create trigger trg_pagos_proteger
  before update on pagos
  for each row execute function fn_pagos_proteger();

-- security_invoker: la vista se consulta con los permisos de quien la usa y
-- respeta RLS. Sin esto, PostgreSQL la ejecuta como su dueño (que no pasa por
-- RLS) y mostraría los saldos de todas las agencias.
create view v_facturas_saldo with (security_invoker = true) as
select
  f.id                               as factura_id,
  f.agencia_id,
  f.numero_factura,
  f.cliente_id,
  f.fecha,
  f.total,
  f.estado,
  coalesce(p.pagado, 0)::numeric(18,2)            as pagado,
  (f.total - coalesce(p.pagado, 0))::numeric(18,2) as saldo,
  case
    when f.estado = 'ANULADA'           then 'ANULADA'
    when coalesce(p.pagado, 0) >= f.total then 'PAGADA'
    when coalesce(p.pagado, 0) = 0        then 'PENDIENTE'
    else 'PARCIAL'
  end                                as estado_pago
from facturas f
left join (
  select factura_id, sum(monto) as pagado
  from pagos
  where estado = 'APLICADO'
  group by factura_id
) p on p.factura_id = f.id;


-- =====================================================================
-- 13. Entregas
-- =====================================================================
-- Un paquete puede tener varios intentos de entrega (uno fallido y otro
-- exitoso), pero solo uno vigente a la vez.

create table entregas (
  id                      bigint generated by default as identity primary key,
  agencia_id              bigint       not null default fn_agencia_actual(),
  paquete_id              bigint       not null,
  tipo_entrega            varchar(20)  not null check (tipo_entrega in ('RETIRO_EN_AGENCIA', 'DELIVERY')),
  direccion               text,
  estado                  varchar(20)  not null default 'PENDIENTE'
                          check (estado in ('PENDIENTE', 'EN_RUTA', 'ENTREGADA', 'FALLIDA', 'CANCELADA')),
  fecha_programada        timestamptz,
  fecha_entrega           timestamptz,
  persona_recibe          varchar(150),
  responsable_usuario_id  bigint,
  observaciones           text,
  creado_por_usuario_id   bigint       not null,
  creado_en               timestamptz  not null default now(),
  actualizado_en          timestamptz  not null default now(),
  constraint fk_entregas_paquete foreign key (paquete_id, agencia_id) references paquetes (id, agencia_id),
  constraint fk_entregas_responsable foreign key (responsable_usuario_id, agencia_id) references usuarios (id, agencia_id),
  constraint fk_entregas_creado_por foreign key (creado_por_usuario_id, agencia_id) references usuarios (id, agencia_id),
  constraint ck_entregas_direccion check (
    tipo_entrega <> 'DELIVERY' or nullif(btrim(direccion), '') is not null
  ),
  constraint ck_entregas_en_ruta check (
    estado <> 'EN_RUTA' or (tipo_entrega = 'DELIVERY' and responsable_usuario_id is not null)
  ),
  constraint ck_entregas_entregada check (
    estado <> 'ENTREGADA' or (fecha_entrega is not null and nullif(btrim(persona_recibe), '') is not null)
  )
);
