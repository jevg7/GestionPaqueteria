-- Fuente de verdad de los estados. Inmutable: solo se inserta.

create table historial_estados_paquete (
  id              bigint generated by default as identity primary key,
  agencia_id      bigint      not null default fn_agencia_actual(),
  paquete_id      bigint      not null,
  estado_id       smallint    not null references estados_paquete (id),
  usuario_id      bigint      not null,
  fecha           timestamptz not null default now(),
  observacion     text,
  constraint fk_historial_paquete foreign key (paquete_id, agencia_id) references paquetes (id, agencia_id),
  constraint fk_historial_usuario foreign key (usuario_id, agencia_id) references usuarios (id, agencia_id)
);
create index ix_historial_paquete_fecha on historial_estados_paquete (paquete_id, fecha);
create index ix_historial_estado_fecha on historial_estados_paquete (estado_id, fecha);
create index ix_historial_usuario on historial_estados_paquete (usuario_id);

-- Al insertar historial: actualiza estado_actual_id y las fechas de recepción.
-- Rechaza cambios desde un estado final (ENTREGADO, CANCELADO).
create or replace function fn_historial_aplicar_estado()
returns trigger
language plpgsql
set search_path = paqueteria, public
as $$
declare
  v_codigo_nuevo  text;
  v_actual_final  boolean;
  v_actual_codigo text;
begin
  select e.es_final, e.codigo into v_actual_final, v_actual_codigo
  from paquetes p join estados_paquete e on e.id = p.estado_actual_id
  where p.id = new.paquete_id
  for update of p;

  if v_actual_final and new.estado_id <> (select estado_actual_id from paquetes where id = new.paquete_id) then
    raise exception 'El paquete % está en estado final (%) y no puede cambiar de estado',
      new.paquete_id, v_actual_codigo
      using errcode = 'check_violation';
  end if;

  select codigo into v_codigo_nuevo from estados_paquete where id = new.estado_id;

  update paquetes p set
    estado_actual_id = new.estado_id,
    fecha_recepcion_miami = case when v_codigo_nuevo = 'RECIBIDO_EN_MIAMI'
                                 then coalesce(p.fecha_recepcion_miami, new.fecha)
                                 else p.fecha_recepcion_miami end,
    fecha_recepcion_nicaragua = case when v_codigo_nuevo = 'RECIBIDO_EN_NICARAGUA'
                                     then coalesce(p.fecha_recepcion_nicaragua, new.fecha)
                                     else p.fecha_recepcion_nicaragua end
  where p.id = new.paquete_id;

  return null;
end $$;

create trigger trg_historial_aplicar_estado
  after insert on historial_estados_paquete
  for each row execute function fn_historial_aplicar_estado();

