create table paquetes (
  id                          bigint generated by default as identity primary key,
  agencia_id                  bigint        not null default fn_agencia_actual(),
  codigo_paquete              varchar(20)   not null
                              default fn_formatear_codigo('PKG-', fn_siguiente_correlativo('PKG'), 6),
  cliente_id                  bigint        not null,
  tracking_externo            varchar(100),
  tienda                      varchar(100),
  descripcion                 text          not null,
  metodo_envio_id             smallint      not null references metodos_envio (id),
  -- Estado actual (denormalizado). Solo cambia insertando en historial_estados_paquete.
  estado_actual_id            smallint      not null default 1 references estados_paquete (id),
  embarque_id                 bigint,
  peso_lb                     numeric(10,2) check (peso_lb > 0),
  tarifa_id                   integer,
  tarifa_aplicada             numeric(12,4) check (tarifa_aplicada > 0),  -- copia del precio al calcular
  monto_calculado             numeric(18,2) check (monto_calculado >= 0),
  registrado_por_usuario_id   bigint        not null,
  fecha_registro              timestamptz   not null default now(),
  fecha_recepcion_miami       timestamptz,  -- la llena el historial
  fecha_recepcion_nicaragua   timestamptz,  -- la llena el historial
  actualizado_en              timestamptz   not null default now(),

  constraint uq_paquetes_codigo unique (agencia_id, codigo_paquete),
  constraint uq_paquetes_id_agencia unique (id, agencia_id),
  constraint fk_paquetes_cliente foreign key (cliente_id, agencia_id) references clientes (id, agencia_id),
  constraint fk_paquetes_registrado_por foreign key (registrado_por_usuario_id, agencia_id) references usuarios (id, agencia_id),
  -- El embarque debe ser del mismo método de envío (y de la misma agencia) que el paquete.
  constraint fk_paquetes_embarque_mismo_metodo
    foreign key (embarque_id, metodo_envio_id, agencia_id) references embarques (id, metodo_envio_id, agencia_id),
  -- La tarifa aplicada debe ser del mismo método de envío (y de la misma agencia) que el paquete.
  constraint fk_paquetes_tarifa_mismo_metodo
    foreign key (tarifa_id, metodo_envio_id, agencia_id) references tarifas_envio (id, metodo_envio_id, agencia_id),
  -- El cálculo se registra completo o no se registra.
  constraint ck_paquetes_calculo_completo check (
    (tarifa_id is null and tarifa_aplicada is null and monto_calculado is null)
    or (peso_lb is not null and tarifa_id is not null and tarifa_aplicada is not null and monto_calculado is not null)
  )
);
create index ix_paquetes_cliente on paquetes (cliente_id);
create index ix_paquetes_estado on paquetes (agencia_id, estado_actual_id);
create index ix_paquetes_embarque on paquetes (embarque_id) where embarque_id is not null;
create index ix_paquetes_metodo on paquetes (metodo_envio_id);
create index ix_paquetes_tarifa on paquetes (tarifa_id) where tarifa_id is not null;
create index ix_paquetes_registrado_por on paquetes (registrado_por_usuario_id);
create index ix_paquetes_fecha_registro on paquetes (agencia_id, fecha_registro);
-- Un tracking externo no puede estar registrado dos veces en la misma agencia
-- (salvo paquetes cancelados, id 11).
create unique index uq_paquetes_tracking_vigente on paquetes (agencia_id, upper(tracking_externo))
  where tracking_externo is not null and estado_actual_id <> 11;

-- Alta de paquete: siempre nace en REGISTRADO (id 1), sin embarque, sin
-- cálculo y sin fechas de recepción. Todo eso lo produce el flujo después.
create or replace function fn_paquetes_validar_alta()
returns trigger
language plpgsql
as $$
begin
  new.estado_actual_id := coalesce(new.estado_actual_id, 1);

  if new.estado_actual_id <> 1
     or new.embarque_id is not null
     or new.peso_lb is not null
     or new.tarifa_id is not null
     or new.tarifa_aplicada is not null
     or new.monto_calculado is not null
     or new.fecha_recepcion_miami is not null
     or new.fecha_recepcion_nicaragua is not null then
    raise exception 'Un paquete nuevo debe crearse en estado REGISTRADO, sin embarque, peso, tarifa, monto ni fechas de recepción'
      using errcode = 'check_violation';
  end if;

  return new;
end $$;

create trigger trg_paquetes_validar_alta
  before insert on paquetes
  for each row execute function fn_paquetes_validar_alta();

-- Paquete incluido en una factura vigente: su cliente y los datos del cálculo
-- quedan congelados, porque la factura se emitió con ellos. Para corregirlos
-- hay que anular la factura primero.
create or replace function fn_paquetes_proteger_facturado()
returns trigger
language plpgsql
set search_path = paqueteria, public
as $$
begin
  if (new.cliente_id, new.metodo_envio_id, new.peso_lb, new.tarifa_id, new.tarifa_aplicada, new.monto_calculado)
     is distinct from
     (old.cliente_id, old.metodo_envio_id, old.peso_lb, old.tarifa_id, old.tarifa_aplicada, old.monto_calculado)
  and exists (
    select 1
    from detalles_factura d
    join facturas f on f.id = d.factura_id
    where d.paquete_id = old.id
      and f.estado <> 'ANULADA'
  ) then
    raise exception 'El paquete % está en una factura vigente: no se puede cambiar su cliente, método, peso, tarifa ni monto', old.id
      using errcode = 'restrict_violation';
  end if;

  return new;
end $$;

create trigger trg_paquetes_proteger_facturado
  before update of cliente_id, metodo_envio_id, peso_lb, tarifa_id, tarifa_aplicada, monto_calculado on paquetes
  for each row execute function fn_paquetes_proteger_facturado();


