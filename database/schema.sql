-- =====================================================================
-- 14. Auditoría
-- =====================================================================
-- Cada INSERT, UPDATE y DELETE de las tablas de negocio queda aquí por un
-- trigger, venga de la API, de otro trigger o de SQL manual. La API pasa quién
-- y desde dónde en variables de sesión (paqueteria.usuario_id,
-- paqueteria.origen, paqueteria.trace_id). Inmutable.

create table audit_logs (
  id                  bigint generated by default as identity primary key,
  agencia_id          bigint,                         -- null: cambio de la plataforma sin agencia
  fecha               timestamptz  not null default now(),
  usuario_id          bigint,                         -- sin FK: la auditoría nunca bloquea una operación
  tabla               varchar(63)  not null,
  registro_id         varchar(100) not null,
  accion              varchar(10)  not null check (accion in ('INSERT', 'UPDATE', 'DELETE')),
  valores_anteriores  jsonb,
  valores_nuevos      jsonb,
  origen              varchar(200),
  trace_id            varchar(100)
);
create index ix_audit_logs_registro on audit_logs (tabla, registro_id, id);
create index ix_audit_logs_usuario on audit_logs (usuario_id, id);
create index ix_audit_logs_fecha on audit_logs (agencia_id, fecha);

-- Registra el cambio de la fila. Argumentos del trigger: las columnas de la
-- clave primaria. En UPDATE guarda solo las columnas que cambiaron (sin
-- actualizado_en); si solo cambió actualizado_en no registra nada.
create or replace function fn_auditar()
returns trigger
language plpgsql
set search_path = paqueteria, public
as $$
declare
  v_nuevo    jsonb := case when tg_op <> 'DELETE' then to_jsonb(new) end;
  v_anterior jsonb := case when tg_op <> 'INSERT' then to_jsonb(old) end;
  v_fila     jsonb := coalesce(v_nuevo, v_anterior);
  v_id       text;
  v_columna  text;
begin
  foreach v_columna in array tg_argv loop
    v_id := concat_ws(',', v_id, v_fila ->> v_columna);
  end loop;

  if tg_op = 'UPDATE' then
    select jsonb_object_agg(n.key, o.value), jsonb_object_agg(n.key, n.value)
      into v_anterior, v_nuevo
    from jsonb_each(to_jsonb(new)) n
    join jsonb_each(to_jsonb(old)) o on o.key = n.key
    where n.value is distinct from o.value
      and n.key <> 'actualizado_en';

    if v_nuevo is null then
      return null;
    end if;
  end if;

  insert into audit_logs (agencia_id, usuario_id, tabla, registro_id, accion, valores_anteriores, valores_nuevos, origen, trace_id)
  values (
    -- La agencia de la fila; en la tabla agencias, la propia agencia.
    coalesce((v_fila ->> 'agencia_id')::bigint, case when tg_table_name = 'agencias' then (v_fila ->> 'id')::bigint end),
    nullif(current_setting('paqueteria.usuario_id', true), '')::bigint,
    tg_table_name,
    v_id,
    tg_op,
    v_anterior,
    v_nuevo,
    nullif(current_setting('paqueteria.origen', true), ''),
    nullif(current_setting('paqueteria.trace_id', true), ''));
  return null;
end $$;

create or replace function fn_auditoria_inmutable()
returns trigger
language plpgsql
as $$
begin
  raise exception 'La auditoría es inmutable'
    using errcode = 'restrict_violation';
end $$;

create trigger trg_audit_logs_inmutable
  before update on audit_logs
  for each row execute function fn_auditoria_inmutable();

-- Tablas auditadas y su clave primaria. No se auditan correlativos (contadores
-- técnicos) ni historial_estados_paquete (ya registra cada cambio de estado).
do $$
declare
  v_tabla record;
begin
  for v_tabla in
    select * from (values
      ('agencias', 'id'), ('usuarios_plataforma', 'id'),
      ('usuarios', 'id'), ('roles', 'id'), ('usuario_roles', 'usuario_id,rol_id'),
      ('metodos_envio', 'id'), ('estados_paquete', 'id'), ('ubicaciones', 'id'), ('rutas', 'id'),
      ('tarifas_envio', 'id'), ('tipos_cambio', 'id'), ('clientes', 'id'), ('embarques', 'id'),
      ('paquetes', 'id'), ('facturas', 'id'), ('detalles_factura', 'id'), ('pagos', 'id'), ('entregas', 'id')
    ) as t(nombre, clave)
  loop
    execute format(
      'create trigger %I after insert or update or delete on %I for each row execute function fn_auditar(%s)',
      'trg_' || v_tabla.nombre || '_auditoria', v_tabla.nombre,
      (select string_agg(quote_literal(c), ', ') from unnest(string_to_array(v_tabla.clave, ',')) c));
  end loop;
end $$;


-- =====================================================================
-- 15. Triggers de actualizado_en y política de no borrado
-- =====================================================================

do $$
declare
  v_tabla text;
begin
  foreach v_tabla in array array[
    'agencias', 'usuarios_plataforma', 'usuarios', 'metodos_envio', 'tarifas_envio', 'tipos_cambio',
    'clientes', 'embarques', 'paquetes', 'facturas', 'pagos', 'entregas'
  ] loop
    execute format(
      'create trigger %I before update on %I for each row execute function fn_set_actualizado_en()',
      'trg_' || v_tabla || '_actualizado', v_tabla);
  end loop;

  -- Ninguna tabla admite DELETE ni TRUNCATE. Única excepción: usuario_roles,
  -- porque quitar un rol a un usuario es una operación normal. Esta es la
  -- segunda capa; la primera es que el rol de la API no tiene privilegios de
  -- DELETE ni TRUNCATE (sección 18).
  foreach v_tabla in array array[
    'agencias', 'usuarios_plataforma', 'correlativos', 'usuarios', 'roles', 'metodos_envio',
    'estados_paquete', 'ubicaciones', 'rutas', 'tarifas_envio', 'tipos_cambio', 'clientes', 'embarques',
    'paquetes', 'historial_estados_paquete', 'facturas', 'detalles_factura', 'pagos', 'entregas', 'audit_logs'
  ] loop
    execute format(
      'create trigger %I before delete on %I for each row execute function fn_impedir_borrado()',
      'trg_' || v_tabla || '_sin_borrado', v_tabla);
    execute format(
      'create trigger %I before truncate on %I for each statement execute function fn_impedir_borrado()',
      'trg_' || v_tabla || '_sin_truncate', v_tabla);
  end loop;
end $$;


